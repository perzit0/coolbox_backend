def _seed_sedes():
    for codigo, nombre, direccion, distrito, lat, lng, horario in SEDES:
        sede = Sede.query.filter_by(codigo=codigo).first()
        if not sede:
            db.session.add(
                Sede(
                    codigo=codigo,
                    nombre=nombre,
                    direccion=direccion,
                    distrito=distrito,
                    lat=lat,
                    lng=lng,
                    horario=horario,
                )
            )
    db.session.commit()


def _por_codigo(*codigos):
    return [p for p in Producto.query.filter(Producto.codigo.in_(codigos)).all()]


def _promo(nombre, tipo, dias, **kw):
    """Crea la promoción demo solo si no existe una con el mismo nombre."""
    if Promocion.query.filter_by(nombre=nombre).first():
        return None
    inicio = ahora() - timedelta(days=1)
    productos = kw.pop("productos", [])
    precios = kw.pop("precios", {})
    p = Promocion(
        nombre=nombre, tipo=tipo, fecha_inicio=inicio, fecha_fin=inicio + timedelta(days=dias), activa=True, **kw
    )
    db.session.add(p)
    db.session.flush()
    for prod in productos:
        db.session.add(
            PromocionProducto(promocion_id=p.id, producto_id=prod.id, precio_especial=precios.get(prod.codigo))
        )
    return p


